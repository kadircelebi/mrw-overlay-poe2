const tables = { en, tr, 'zh-Hant': zh };
const locales = { en: 'en-US', tr: 'tr-TR', 'zh-Hant': 'zh-TW' };
let lang = 'en';

export function setLang(value) {
  lang = Object.hasOwn(tables, value) ? value : 'en';
  return lang;
}
export const currentLang = () => lang;
export const locale = () => locales[lang];

export function t(key, ...args) {
  const text = tables[lang][key] ?? en[key] ?? key;
  return text.replace(/\{(\d+)\}/g, (match, i) => (args[i] === undefined ? match : String(args[i])));
}

export const num = (value, digits = 6) => value.toLocaleString(locale(), { maximumFractionDigits: digits });

