func loadShot(t *testing.T) (Img, Grid) {
	shot := os.Getenv("INVSCAN_SHOT")
	if shot == "" {
		t.Skip("INVSCAN_SHOT not set")
	}
	f, err := os.Open(shot)
	if err != nil {
		t.Fatal(err)
	}
	src, _, err := image.Decode(f)
	f.Close()
	if err != nil {
		t.Fatal(err)
	}
	b := src.Bounds()
	pic := FromImage(src, b)
	return pic, Align(pic, InventoryGuess(b.Dx(), b.Dy()))
}

var fontExamples = 8

// TestLocalFontGen writes font.go (INVSCAN_FONT_OUT) from INVSCAN_SHOT, a
// 3840×2160 picture of the inventory above.
func TestLocalFontGen(t *testing.T) {
	outPath := os.Getenv("INVSCAN_FONT_OUT")
	if outPath == "" {
		t.Skip("INVSCAN_FONT_OUT not set")
	}
	pic, g := loadShot(t)
	figs := map[rune][]figure{}
	collect := func(want map[[2]int]string, corner [4]float64, fromRight bool) {
		keys := make([][2]int, 0, len(want))
		for at := range want {
			keys = append(keys, at)
		}
		sort.Slice(keys, func(i, j int) bool { return keys[i][0]*100+keys[i][1] < keys[j][0]*100+keys[j][1] })
		for _, at := range keys {
			s := want[at]
			wide := g.Rect(at[1], at[0]).Inset(-Pad(g.Cell) / 2)
			boxes := figureBoxes(pic, wide, corner)
			n := len([]rune(s))
			if len(boxes) < n {
				t.Errorf("r%d c%d: %d figures for %q", at[0], at[1], len(boxes), s)
				continue
			}
			// The icon's own white may lie past the number.
			if fromRight {
				boxes = boxes[len(boxes)-n:]
			} else {
				boxes = boxes[:n]
			}
			k := float64(figCell) / float64(wide.Dx())
			for i, r := range s {
				box := boxes[i].Inset(-figOutline)
				w := whiteness(pic.crop(box))
				w = w.Resize(max(1, int(float64(w.W)*k+0.5)), max(1, int(float64(w.H)*k+0.5)))
				fg := figure{R: r, W: w.W, H: w.H, Pix: make([]uint8, w.W*w.H)}
				for p := range fg.Pix {
					fg.Pix[p] = uint8(w.Pix[p*3] + 0.5)
				}
				figs[r] = append(figs[r], fg)
			}
		}
	}
	collect(stackWant, stackCorner, false)
	collect(cornerWant, tierCorner, true)

	// More bottom-right figures from other pictures of the same 4K screen:
	// INVSCAN_EXTRA is "picture;x0,y0,x1,y1;text" items joined by "|" (a
	// cell and the number written in its corner, e.g. a Thaumaturgic Flux's
	// "XIX" in the Currency tab).
	for _, item := range strings.Split(os.Getenv("INVSCAN_EXTRA"), "|") {
		parts := strings.Split(item, ";")
		if len(parts) != 3 {
			continue
		}
		f, err := os.Open(parts[0])
		if err != nil {
			t.Fatal(err)
		}
		src, _, err := image.Decode(f)
		f.Close()
		if err != nil {
			t.Fatal(err)
		}
		other := FromImage(src, src.Bounds())
		var cell image.Rectangle
		fmt.Sscanf(parts[1], "%d,%d,%d,%d", &cell.Min.X, &cell.Min.Y, &cell.Max.X, &cell.Max.Y)
		wide := cell.Inset(-Pad(float64(cell.Dx())) / 2)
		boxes := figureBoxes(other, wide, tierCorner)
		n := len([]rune(parts[2]))
		if len(boxes) < n {
			t.Errorf("%s: %d figures for %q", parts[1], len(boxes), parts[2])
			continue
		}
		boxes = boxes[len(boxes)-n:]
		k := float64(figCell) / float64(wide.Dx())
		for i, r := range parts[2] {
			w := whiteness(other.crop(boxes[i].Inset(-figOutline)))
			w = w.Resize(max(1, int(float64(w.W)*k+0.5)), max(1, int(float64(w.H)*k+0.5)))
			fg := figure{R: r, W: w.W, H: w.H, Pix: make([]uint8, w.W*w.H)}
			for p := range fg.Pix {
				fg.Pix[p] = uint8(w.Pix[p*3] + 0.5)
			}
			figs[r] = append(figs[r], fg)
		}
	}

	var keys []rune
	for r := range figs {
		keys = append(keys, r)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	var sb strings.Builder
	sb.WriteString("package invscan\n\n// Code generated by TestLocalFontGen from a 3840×2160 inventory; DO NOT EDIT.\n\n")
	fmt.Fprintf(&sb, "// font holds the game's figures as they look at a %d-pixel cell: each\n// pixel's darkest channel, outline included.\n", figCell)
	sb.WriteString("var font = []figure{\n")
	for _, r := range keys {
		// Up to fontExamples of each figure, spread over the cells they came
		// from: each cell draws a figure a little differently.
		list := figs[r]
		if n := os.Getenv("INVSCAN_FONT_N"); n != "" {
			fmt.Sscan(n, &fontExamples)
		}
		if len(list) > fontExamples {
			step := float64(len(list)) / float64(fontExamples)
			var picked []figure
			for i := 0; i < fontExamples; i++ {
				picked = append(picked, list[int(float64(i)*step)])
			}
			list = picked
		}
		for _, f := range list {
			fmt.Fprintf(&sb, "\t{R: %q, W: %d, H: %d, Pix: []uint8{", f.R, f.W, f.H)
			for i, v := range f.Pix {
				if i > 0 {
					sb.WriteString(", ")
				}
				fmt.Fprintf(&sb, "%d", v)
			}
			sb.WriteString("}},\n")
		}
		t.Logf("%q: %d examples", r, len(figs[r]))
	}
	sb.WriteString("}\n")
	if err := os.WriteFile(outPath, []byte(sb.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestLocalMarks reads every listed cell's figures of INVSCAN_SHOT against
// the known ones (the same inventory at any resolution).
func TestLocalMarks(t *testing.T) {
	pic, g := loadShot(t)
	bad := 0
	start := time.Now()
	for at := range inventoryWant {
		ReadMarks(pic, g.Rect(at[1], at[0]))
	}
	t.Logf("%d cells' marks read in %v (one thread)", len(inventoryWant), time.Since(start))
	for at, name := range inventoryWant {
		if name == "" {
			continue // not on the list: its marks are not read
		}
		m := ReadMarks(pic, g.Rect(at[1], at[0]))
		wantStack := 1
		if s, ok := stackWant[at]; ok {
			wantStack, _ = number(s)
		}
		wantTier := map[string]int{"II": 2, "III": 3}[cornerWant[at]]
		if m.Stack != wantStack || m.Corner != wantTier || m.Unsure {
			bad++
			t.Errorf("r%d c%d %s: got %+v, want stack %d tier %d", at[0], at[1], name, m, wantStack, wantTier)
		}
	}
	t.Logf("%d cells wrong", bad)
}
